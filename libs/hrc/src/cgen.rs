fn sanitize(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c);
        } else if !out.ends_with('_') {
            out.push('_');
        }
        if out.len() > 40 {
            break;
        }
    }
    out
}

fn c_string(bytes: &[u8]) -> String {
    let mut s = String::from("\"");
    let mut prev_hex = false;
    for &b in bytes {
        match b {
            b'"' => s.push_str("\\\""),
            b'\\' => s.push_str("\\\\"),
            b'\n' => s.push_str("\\n"),
            b'\t' => s.push_str("\\t"),
            b'\r' => s.push_str("\\r"),
            // A hex escape swallows following hex digits; break the string.
            b'0'..=b'9' | b'a'..=b'f' | b'A'..=b'F' if prev_hex => {
                s.push_str("\" \"");
                s.push(b as char);
            }
            32..=126 => s.push(b as char),
            _ => {
                let _ = write!(s, "\\x{:02x}", b);
                prev_hex = true;
                continue;
            }
        }
        prev_hex = false;
    }
    s.push('"');
    s
}

fn is_zst_c(t: &Ty) -> bool {
    matches!(t, Ty::Never | Ty::FnDef(..)) || t.is_unit()
}

impl<'a> Gen<'a> {
    fn fresh(&mut self, prefix: &str) -> String {
        self.n += 1;
        format!("{}{}", prefix, self.n)
    }

    fn tyname(&self, t: &Ty) -> String {
        crate::ty::display(t, &|d| self.db.path_name(d))
    }

    // ---- types ----

    fn int_c(i: IntTy) -> &'static str {
        match i {
            IntTy::I8 => "int8_t",
            IntTy::I16 => "int16_t",
            IntTy::I32 => "int32_t",
            IntTy::I64 | IntTy::Isize | IntTy::I128 => "int64_t",
            IntTy::U8 => "uint8_t",
            IntTy::U16 => "uint16_t",
            IntTy::U32 => "uint32_t",
            IntTy::U64 | IntTy::Usize | IntTy::U128 => "uint64_t",
        }
    }

    fn is_box(&self, t: &Ty) -> Option<Ty> {
        match t {
            Ty::Adt(d, a) if self.db.is_lang(*d, "Box") => Some(a[0].clone()),
            _ => None,
        }
    }

    /// The C type of a pointer to `inner` (fat for unsized types).
    fn ptr_to(&mut self, inner: &Ty) -> String {
        match inner {
            Ty::Str => String::from("hrc_str"),
            Ty::Dyn(_) => String::from("hrc_dyn"),
            Ty::Slice(e) => self.slice_ty(e),
            t => format!("{}*", self.name_only(t)),
        }
    }

    fn slice_ty(&mut self, elem: &Ty) -> String {
        let key = Ty::Ref(false, Rc::new(Ty::Slice(Rc::new(elem.clone()))));
        if let Some(n) = self.names.get(&key) {
            return n.clone();
        }
        let n = self.fresh("S");
        self.names.insert(key, n.clone());
        let e = self.name_only(elem);
        let _ = writeln!(self.fwd, "typedef struct {{ {} *ptr; uint64_t len; }} {};", e, n);
        n
    }

    /// A type's name, with only a forward declaration for structs.
    fn name_only(&mut self, t: &Ty) -> String {
        match t {
            Ty::Int(i) => String::from(Self::int_c(*i)),
            Ty::Float(FloatTy::F32) => String::from("float"),
            Ty::Float(FloatTy::F64) => String::from("double"),
            Ty::Bool => String::from("uint8_t"),
            Ty::Char => String::from("uint32_t"),
            Ty::Never | Ty::FnDef(..) => String::from("hrc_unit"),
            Ty::Tuple(ts) if ts.is_empty() => String::from("hrc_unit"),
            Ty::Ref(_, inner) | Ty::Ptr(_, inner) => {
                let inner = (**inner).clone();
                self.ptr_to(&inner)
            }
            Ty::Adt(..) if self.is_box(t).is_some() => {
                let inner = self.is_box(t).unwrap();
                self.ptr_to(&inner)
            }
            Ty::FnPtr(..) => self.ctype(t),
            _ => {
                if let Some(n) = self.names.get(t) {
                    return n.clone();
                }
                let n = self.fresh("T");
                self.names.insert(t.clone(), n.clone());
                let _ = writeln!(self.fwd, "typedef struct {} {}; /* {} */", n, n, self.tyname(t).replace("*/", "* /"));
                n
            }
        }
    }

    /// A type's name with its definition emitted (for by-value use).
    fn ctype(&mut self, t: &Ty) -> String {
        match t {
            Ty::FnPtr(ps, r) => {
                if let Some(n) = self.names.get(t) {
                    return n.clone();
                }
                let n = self.fresh("F");
                self.names.insert(t.clone(), n.clone());
                let r = self.ctype(r);
                let ps: Vec<String> = ps.iter().map(|p| self.ctype(p)).collect();
                let _ = writeln!(self.defs, "typedef {} (*{})({});", r, n, ps.join(", "));
                n
            }
            Ty::Tuple(_) | Ty::Array(..) | Ty::Adt(..) | Ty::Closure(_) if !(t.is_unit() || self.is_box(t).is_some()) => {
                let n = self.name_only(t);
                if !self.defined.contains(t) {
                    self.defined.insert(t.clone());
                    self.define(t, &n);
                }
                n
            }
            _ => self.name_only(t),
        }
    }

    fn define(&mut self, t: &Ty, n: &str) {
        let mut body = String::new();
        match t {
            Ty::Tuple(ts) => {
                for (i, e) in ts.iter().enumerate() {
                    let c = self.ctype(e);
                    let _ = write!(body, " {} f{};", c, i);
                }
            }
            Ty::Array(e, len) => {
                let c = self.ctype(e);
                let len = match &**len {
                    Ty::Const(n) => *n,
                    _ => 0,
                };
                // `[T; 0]` keeps an element so that `.a` exists.
                let _ = write!(body, " {} a[{}];", c, len.max(1));
            }
            Ty::Closure(id) => {
                let caps = self.p.closures[*id as usize].captures.clone();
                for (i, (ct, _)) in caps.iter().enumerate() {
                    let c = self.ctype(ct);
                    let _ = write!(body, " {} c{};", c, i);
                }
            }
            Ty::Adt(def, substs) => {
                let info = self.adt_fields(*def, substs);
                let is_enum = matches!(self.db.def(*def).kind, DefKind::Enum(_));
                if is_enum {
                    body.push_str(" int64_t tag;");
                    let mut u = String::new();
                    for (vi, fields) in info.iter().enumerate() {
                        if fields.is_empty() {
                            continue;
                        }
                        let mut s = String::new();
                        for (i, f) in fields.iter().enumerate() {
                            let c = self.ctype(f);
                            let _ = write!(s, " {} f{};", c, i);
                        }
                        let _ = write!(u, " struct {{{} }} v{};", s, vi);
                    }
                    if !u.is_empty() {
                        let _ = write!(body, " union {{{} }} u;", u);
                    }
                } else {
                    for (i, f) in info[0].iter().enumerate() {
                        let c = self.ctype(f);
                        let _ = write!(body, " {} f{};", c, i);
                    }
                }
            }
            _ => {}
        }
        if body.is_empty() {
            body.push_str(" uint8_t _;");
        }
        let _ = writeln!(self.defs, "struct {} {{{} }};", n, body);
    }

    /// Field types of each variant (one for structs).
    fn adt_fields(&self, def: DefId, substs: &[Ty]) -> Vec<Vec<Ty>> {
        if let Some(f) = self.p.adt_fields.get(&Ty::Adt(def, substs.to_vec().into())) {
            return f.clone();
        }
        match self.p.layouts.get(&def) {
            Some(l) => l.variants.iter().map(|v| v.iter().map(|t| t.subst(substs)).collect()).collect(),
            None => alloc::vec![Vec::new()],
        }
    }

    fn enum_disc(&self, variant: DefId) -> i128 {
        let d = self.db.def(variant);
        match (d.parent, &d.kind) {
            (Some(e), DefKind::Variant(i)) => self.p.layouts.get(&e).map(|l| l.discs[*i]).unwrap_or(*i as i128),
            _ => 0,
        }
    }

    // ---- constants ----

    fn str_const(&mut self, s: &Rc<str>) -> String {
        if let Some(n) = self.strs.get(s) {
            return n.clone();
        }
        let n = self.fresh("STR");
        let _ = writeln!(self.consts, "static hrc_str {} = {{(uint8_t *){}, {}}};", n, c_string(s.as_bytes()), s.len());
        self.strs.insert(s.clone(), n.clone());
        n
    }

    fn loc_const(&mut self, span: Span) -> String {
        if let Some(n) = self.locs.get(&span) {
            return n.clone();
        }
        let file = self.sources.names.get(span.file as usize).cloned().unwrap_or_default();
        let loc_ty = Ty::Adt(self.db.lang("Location"), Rc::from([]));
        let lt = self.ctype(&loc_ty);
        let n = self.fresh("LOC");
        let _ = writeln!(
            self.consts,
            "static {} {} = {{{{(uint8_t *){}, {}}}, {}, {}}};",
            lt,
            n,
            c_string(file.as_bytes()),
            file.len(),
            span.line,
            span.col
        );
        self.locs.insert(span, n.clone());
        n
    }

    fn fn_name(&self, id: tir::InstId) -> String {
        format!("f{}_{}", id, sanitize(&self.p.fns[id as usize].name))
    }

    fn extern_name(&self, def: DefId) -> String {
        String::from(&*self.db.def(def).name)
    }

    fn fn_sig(&mut self, id: tir::InstId) -> String {
        let f = &self.p.fns[id as usize];
        let ret = f.ret.clone();
        let params: Vec<(tir::LocalId, Ty)> = f.params.iter().map(|l| (*l, f.locals[*l as usize].ty.clone())).collect();
        let tc = f.track_caller;
        let r = self.ctype(&ret);
        let mut ps: Vec<String> = params.iter().map(|(l, t)| format!("{} l{}", self.ctype(t), l)).collect();
        if tc {
            ps.push(String::from("const void *__loc"));
        }
        if ps.is_empty() {
            ps.push(String::from("void"));
        }
        format!("static {} {}({})", r, self.fn_name(id), ps.join(", "))
    }

    fn closure_sig(&mut self, id: u32) -> String {
        let c = &self.p.closures[id as usize];
        let f = &self.p.fns[c.func as usize];
        let ret = c.ret.clone();
        let params: Vec<(tir::LocalId, Ty)> = c.params.iter().map(|l| (*l, f.locals[*l as usize].ty.clone())).collect();
        let env = self.ctype(&Ty::Closure(id));
        let r = self.ctype(&ret);
        let mut ps = alloc::vec![format!("{} *env", env)];
        for (l, t) in &params {
            ps.push(format!("{} l{}", self.ctype(t), l));
        }
        format!("static {} c{}({})", r, id, ps.join(", "))
    }

    fn run(&mut self) -> String {
        let mut statics = String::new();
        for i in 0..self.p.fns.len() {
            let s = self.fn_sig(i as u32);
            let _ = writeln!(self.protos, "{};", s);
        }
        for i in 0..self.p.closures.len() {
            let s = self.closure_sig(i as u32);
            let _ = writeln!(self.protos, "{};", s);
        }
        for s in &self.p.statics {
            let t = s.ty.clone();
            let c = self.ctype(&t);
            let _ = writeln!(statics, "static {} g{};", c, s.def);
        }
        for i in 0..self.p.fns.len() {
            let mut fg = FnGen::new(self, Owner::Fn(i as u32));
            let body = fg.function();
            self.fns.push_str(&body);
        }
        for i in 0..self.p.closures.len() {
            let mut fg = FnGen::new(self, Owner::Closure(i as u32));
            let body = fg.function();
            self.fns.push_str(&body);
        }
        // Statics are initialized before main.
        let mut init = FnGen::new(self, Owner::Statics);
        let init_body = init.function();
        self.fns.push_str(&init_body);
        // Vtables.
        for (i, vt) in self.p.vtables.iter().enumerate() {
            let mut entries = Vec::new();
            match &vt.ty {
                Ty::Closure(id) if vt.methods.is_empty() => entries.push(format!("(void *)c{}", id)),
                Ty::FnDef(..) | Ty::FnPtr(..) if vt.methods.is_empty() => {
                    let s = self.fn_value_shim(&vt.ty, vt.fn_inst);
                    entries.push(format!("(void *){}", s));
                }
                _ => {
                    for m in &vt.methods {
                        match m {
                            Some(id) => entries.push(format!("(void *){}", self.fn_name(*id))),
                            None => entries.push(String::from("0")),
                        }
                    }
                }
            }
            if entries.is_empty() {
                entries.push(String::from("0"));
            }
            let _ = writeln!(self.consts, "static void *VT{}[] = {{{}}};", i, entries.join(", "));
        }
        let mut main = String::from("int main(int argc, char **argv) {\n    hrc_rt_init(argc, argv);\n    hrc_init_statics();\n");
        let mret = self.p.fns[self.p.main as usize].ret.clone();
        if let Some(r) = self.p.main_result {
            let t = self.ctype(&mret);
            let _ = writeln!(main, "    {} r = {}();", t, self.fn_name(self.p.main));
            let _ = writeln!(main, "    hrc_exit({}(r));", self.fn_name(r));
        } else {
            let _ = writeln!(main, "    {}();", self.fn_name(self.p.main));
            main.push_str("    hrc_exit(0);\n");
        }
        main.push_str("    return 0;\n}\n");
        let mut ext = String::new();
        for d in self.externs.clone() {
            if let DefKind::ExternFn(f, _) = &self.db.def(d).kind {
                let f = f.clone();
                let _ = writeln!(ext, "{};", self.extern_proto(&f, d));
            }
        }
        let mut out = String::from(PRELUDE);
        out.push_str(&self.fwd);
        out.push_str(&self.defs);
        out.push_str(&ext);
        out.push_str(&statics);
        out.push_str(&self.protos);
        out.push_str("static void hrc_init_statics(void);\n");
        for s in self.shims.values() {
            let first = s.lines().next().unwrap_or("");
            let _ = writeln!(out, "{};", first.trim_end_matches(" {"));
        }
        out.push_str(&self.consts);
        out.push_str(&self.fns);
        for s in self.shims.values() {
            out.push_str(s);
        }
        out.push_str(&main);
        out
    }

    fn extern_proto(&mut self, f: &crate::ast::FnDecl, d: DefId) -> String {
        // Parameter and return types come from the signature table.
        let (ps, r) = self.p.externs.get(&d).cloned().unwrap_or((Vec::new(), crate::ty::unit()));
        let r = self.ctype(&r);
        let mut params: Vec<String> = ps.iter().map(|t| self.ctype(t)).collect();
        if f.variadic {
            params.push(String::from("..."));
        }
        if params.is_empty() {
            params.push(String::from("void"));
        }
        format!("{} {}({})", r, f.name, params.join(", "))
    }

    /// A function `R s(void *env, A...)` calling a function item or pointer.
    fn fn_value_shim(&mut self, t: &Ty, inst: Option<tir::InstId>) -> String {
        let key = format!("fnshim {:?}", t);
        if let Some(s) = self.shims.get(&key) {
            return s.lines().next().unwrap().split('(').next().unwrap().rsplit(' ').next().unwrap().to_string();
        }
        let (ps, r, target) = match t {
            Ty::FnPtr(ps, r) => (ps.to_vec(), (**r).clone(), None),
            Ty::FnDef(..) => {
                let id = inst.unwrap_or(0);
                let f = &self.p.fns[id as usize];
                let ps = f.params.iter().map(|l| f.locals[*l as usize].ty.clone()).collect();
                (ps, f.ret.clone(), Some(id))
            }
            _ => unreachable!(),
        };
        let name = self.fresh("shim");
        let rc = self.ctype(&r);
        let mut params = alloc::vec![String::from("void *env")];
        let mut args = Vec::new();
        for (i, p) in ps.iter().enumerate() {
            let c = self.ctype(p);
            params.push(format!("{} a{}", c, i));
            args.push(format!("a{}", i));
        }
        let callee = match target {
            Some(id) => self.fn_name(id),
            None => {
                let ft = self.ctype(t);
                format!("(*({} *)env)", ft)
            }
        };
        let s = format!("static {} {}({}) {{\n    return {}({});\n}}\n", rc, name, params.join(", "), callee, args.join(", "));
        self.shims.insert(key, s);
        name
    }
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Owner {
    Fn(tir::InstId),
    Closure(u32),
    Statics,
}

#[derive(Clone)]
enum Op {
    Val(String),
    Never,
}

impl Op {
    fn s(&self) -> String {
        match self {
            Op::Val(s) => s.clone(),
            Op::Never => String::from("0"),
        }
    }
}

struct FnGen<'g, 'a> {
    g: &'g mut Gen<'a>,
    owner: Owner,
    func: tir::InstId,
    out: String,
    decls: String,
    indent: usize,
    labels: BTreeMap<u32, (String, String, Option<String>)>,
    track_caller: bool,
    captures: Vec<bool>,
}

fn has_effects(e: &Expr) -> bool {
    match &e.kind {
        K::Int(_) | K::Float(_) | K::Bool(_) | K::Char(_) | K::Str(_) | K::ByteStr(_) | K::Unit | K::Local(_) | K::Upvar(_) | K::Static(_) | K::FnItem | K::Location(_) => false,
        K::Field(x, _) | K::Deref(x) | K::AddrOf(_, x) | K::Cast(x) | K::Unary(_, x) => has_effects(x),
        K::Binary(_, a, b) | K::Index(a, b) => has_effects(a) || has_effects(b),
        _ => true,
    }
}

impl<'g, 'a> FnGen<'g, 'a> {
    fn new(g: &'g mut Gen<'a>, owner: Owner) -> FnGen<'g, 'a> {
        let (func, track_caller, captures) = match owner {
            Owner::Fn(i) => (i, g.p.fns[i as usize].track_caller, Vec::new()),
            Owner::Closure(c) => {
                let cl = &g.p.closures[c as usize];
                (cl.func, false, cl.captures.iter().map(|(_, r)| *r).collect())
            }
            Owner::Statics => (0, false, Vec::new()),
        };
        FnGen {
            g,
            owner,
            func,
            out: String::new(),
            decls: String::new(),
            indent: 1,
            labels: BTreeMap::new(),
            track_caller,
            captures,
        }
    }

    fn line(&mut self, s: &str) {
        for _ in 0..self.indent {
            self.out.push_str("    ");
        }
        self.out.push_str(s);
        self.out.push('\n');
    }

    fn label(&mut self, l: &str) {
        let _ = writeln!(self.out, "{}:;", l);
    }

    fn temp(&mut self, t: &Ty) -> String {
        let c = self.g.ctype(t);
        let n = self.g.fresh("t");
        let _ = writeln!(self.decls, "    {} {};", c, n);
        n
    }

    fn new_label(&mut self) -> String {
        self.g.fresh("L")
    }

    fn loc(&mut self, span: Span) -> String {
        if self.track_caller {
            return String::from("__loc");
        }
        format!("&{}", self.g.loc_const(span))
    }

    fn locals(&self) -> &'a [tir::Local] {
        match self.owner {
            Owner::Statics => &[],
            _ => &self.g.p.fns[self.func as usize].locals,
        }
    }

    fn function(&mut self) -> String {
        let (sig, body, owner_num, params, ret): (String, &'a Expr, u32, Vec<tir::LocalId>, Ty) = match self.owner {
            Owner::Fn(i) => {
                let f = &self.g.p.fns[i as usize];
                let sig = self.g.fn_sig(i);
                (sig, &f.body, 0, f.params.clone(), f.ret.clone())
            }
            Owner::Closure(c) => {
                let cl = &self.g.p.closures[c as usize];
                let sig = self.g.closure_sig(c);
                (sig, &cl.body, c + 1, cl.params.clone(), cl.ret.clone())
            }
            Owner::Statics => return self.statics_init(),
        };
        let locals = self.locals();
        for (i, l) in locals.iter().enumerate() {
            if l.owner == owner_num && !params.contains(&(i as u32)) {
                let c = self.g.ctype(&l.ty);
                let _ = writeln!(self.decls, "    {} l{}; /* {} */", c, i, sanitize(&l.name));
            }
        }
        let v = self.expr(body);
        if let Op::Val(s) = v {
            if !matches!(ret, Ty::Never) {
                if is_zst_c(&ret) {
                    self.line("return 0;");
                } else {
                    self.line(&format!("return {};", s));
                }
            }
        }
        let mut f = format!("{} {{\n", sig);
        f.push_str(&self.decls);
        f.push_str(&self.out);
        f.push_str("}\n\n");
        f
    }

    fn statics_init(&mut self) -> String {
        let statics = &self.g.p.statics;
        for s in statics.iter() {
            for (i, l) in s.locals.iter().enumerate() {
                let c = self.g.ctype(&l.ty);
                let _ = writeln!(self.decls, "    {} l{};", c, i);
            }
            let v = self.expr(&s.init);
            if !is_zst_c(&s.ty) {
                self.line(&format!("g{} = {};", s.def, v.s()));
            }
        }
        let mut f = String::from("static void hrc_init_statics(void) {\n");
        f.push_str(&self.decls);
        f.push_str(&self.out);
        f.push_str("}\n\n");
        f
    }

    // ---- statements and expressions ----

    fn assign_to(&mut self, dst: &str, v: &Op, ty: &Ty) {
        if let Op::Val(s) = v {
            if !is_zst_c(ty) {
                self.line(&format!("{} = {};", dst, s));
            }
        }
    }

    /// Evaluates into a temporary (or returns `0` for zero-sized values).
    fn value_temp(&mut self, e: &'a Expr) -> Op {
        let v = self.expr(e);
        match v {
            Op::Never => Op::Never,
            Op::Val(s) => {
                if is_zst_c(&e.ty) {
                    return Op::Val(String::from("0"));
                }
                let t = self.temp(&e.ty);
                self.line(&format!("{} = {};", t, s));
                Op::Val(t)
            }
        }
    }

    fn operands(&mut self, es: &'a [Expr]) -> Vec<Op> {
        let mut out = Vec::new();
        for (i, e) in es.iter().enumerate() {
            let later = es[i + 1..].iter().any(has_effects);
            let v = if later && !matches!(e.kind, K::Int(_) | K::Float(_) | K::Bool(_) | K::Char(_) | K::Unit | K::Str(_) | K::Location(_)) {
                self.value_temp(e)
            } else {
                self.expr(e)
            };
            out.push(v);
        }
        out
    }

    fn stmt(&mut self, s: &'a Stmt) {
        match s {
            Stmt::Expr(e) => {
                let v = self.expr(e);
                if let Op::Val(x) = v {
                    if x.contains('(') && !is_zst_c(&e.ty) {
                        // Keep calls; drop pure values.
                    }
                }
            }
            Stmt::Let(p, init, els) => {
                let Some(init) = init else { return };
                if let PatKind::Bind(l, None, None) = &p.kind {
                    let v = self.expr(init);
                    let ty = p.ty.clone();
                    self.assign_to(&format!("l{}", l), &v, &ty);
                    return;
                }
                let place = self.place_or_temp(init);
                let Some(place) = place else { return };
                match els {
                    None => {
                        let fail = self.new_label();
                        self.pat(p, &place, &fail);
                        let ok = self.new_label();
                        self.line(&format!("goto {};", ok));
                        self.label(&fail);
                        let l = self.g.loc_const(init.span);
                        self.line(&format!("hrc_unreachable(&{});", l));
                        self.label(&ok);
                    }
                    Some(e) => {
                        let fail = self.new_label();
                        self.pat(p, &place, &fail);
                        let ok = self.new_label();
                        self.line(&format!("goto {};", ok));
                        self.label(&fail);
                        self.expr(e);
                        self.label(&ok);
                    }
                }
            }
        }
    }

    /// A place for an expression: places stay as they are, other values
    /// are stored in a temporary. `None` when it diverges.
    fn place_or_temp(&mut self, e: &'a Expr) -> Option<String> {
        if self.is_place(e) {
            return Some(self.place(e));
        }
        match self.expr(e) {
            Op::Never => None,
            Op::Val(s) => {
                if is_zst_c(&e.ty) {
                    let t = self.temp(&e.ty);
                    return Some(t);
                }
                let t = self.temp(&e.ty);
                self.line(&format!("{} = {};", t, s));
                Some(t)
            }
        }
    }

    fn is_place(&self, e: &Expr) -> bool {
        match &e.kind {
            K::Local(_) | K::Upvar(_) | K::Static(_) => true,
            K::Deref(x) => !e.ty.is_unsized() || self.is_place(x) || true,
            K::Field(x, _) => self.is_place(x),
            K::Index(..) => true,
            K::Block(s, t) if s.len() == 1 => matches!(t.kind, K::Deref(_)) && matches!(&s[0], Stmt::Let(..)),
            _ => false,
        }
    }

    /// An lvalue for a place expression (an unsized place is its fat pointer).
    fn place(&mut self, e: &'a Expr) -> String {
        match &e.kind {
            K::Local(l) => format!("l{}", l),
            K::Upvar(k) => {
                if self.captures.get(*k as usize).copied().unwrap_or(false) {
                    format!("(*env->c{})", k)
                } else {
                    format!("env->c{}", k)
                }
            }
            K::Static(d) => format!("g{}", d),
            K::Deref(x) => {
                let p = self.expr(x).s();
                if e.ty.is_unsized() {
                    p
                } else {
                    format!("(*{})", p)
                }
            }
            K::Field(x, i) => {
                let base = match self.place_or_temp(x) {
                    Some(b) => b,
                    None => return String::from("0"),
                };
                format!("{}.f{}", base, i)
            }
            K::Index(b, i) => {
                let base = match self.place_or_temp(b) {
                    Some(b) => b,
                    None => return String::from("0"),
                };
                let idx = self.value_temp(i).s();
                let span = e.span;
                let loc = self.loc(span);
                match &b.ty {
                    Ty::Array(_, n) => {
                        let n = match &**n {
                            Ty::Const(n) => *n,
                            _ => 0,
                        };
                        self.line(&format!("if ({} >= {}UL) hrc_panic_bounds({}, {}UL, {});", idx, n, idx, n, loc));
                        format!("{}.a[{}]", base, idx)
                    }
                    _ => {
                        self.line(&format!("if ({} >= {}.len) hrc_panic_bounds({}, {}.len, {});", idx, base, idx, base, loc));
                        format!("{}.ptr[{}]", base, idx)
                    }
                }
            }
            _ => match self.place_or_temp(e) {
                Some(p) => p,
                None => String::from("0"),
            },
        }
    }

    fn expr(&mut self, e: &'a Expr) -> Op {
        let span = e.span;
        let v = |s: String| Op::Val(s);
        match &e.kind {
            K::Int(x) => v(self.int_lit(*x, &e.ty)),
            K::Float(f) => v(float_lit(*f, &e.ty)),
            K::Bool(b) => v(String::from(if *b { "1" } else { "0" })),
            K::Char(c) => v(format!("{}U", *c as u32)),
            // A block ending in a diverging statement has a `!` tail.
            K::Unit if matches!(e.ty, Ty::Never) => Op::Never,
            K::Unit | K::FnItem | K::Uninit => v(String::from("0")),
            K::Str(s) => v(self.g.str_const(s)),
            K::ByteStr(b) => {
                let at = match &e.ty {
                    Ty::Ref(_, a) => (**a).clone(),
                    _ => e.ty.clone(),
                };
                let c = self.g.ctype(&at);
                let n = self.g.fresh("BS");
                let bytes: Vec<String> = b.iter().map(|x| x.to_string()).collect();
                let init = if bytes.is_empty() { String::from("0") } else { bytes.join(", ") };
                let _ = writeln!(self.g.consts, "static {} {} = {{{{{}}}}};", c, n, init);
                v(format!("(&{})", n))
            }
            K::Local(_) | K::Upvar(_) | K::Static(_) | K::Field(..) | K::Index(..) => v(self.place(e)),
            K::Deref(_) => v(self.place(e)),
            K::Location(sp) => v(self.loc(*sp)),
            K::Reify(c) => v(self.reify(c, &e.ty)),
            K::AddrOf(_, x) => {
                if x.ty.is_unsized() {
                    return self.expr(x);
                }
                if let K::Deref(inner) = &x.kind {
                    if !x.ty.is_unsized() {
                        return self.expr(inner);
                    }
                }
                let p = if self.is_place(x) {
                    self.place(x)
                } else {
                    match self.place_or_temp(x) {
                        Some(p) => p,
                        None => return Op::Never,
                    }
                };
                v(format!("(&{})", p))
            }
            K::Call(c, args) => self.call(c, args, &e.ty, span),
            K::Unary(op, x) => {
                let a = self.expr(x);
                let Op::Val(a) = a else { return Op::Never };
                match op {
                    UnOp::Neg => {
                        if let (Ty::Int(it), true) = (&e.ty, self.g.checks) {
                            let c = Gen::int_c(*it);
                            let t = self.temp(&e.ty);
                            let loc = self.loc(span);
                            let min = if it.signed() { format!("({})(1UL << {})", c, it.bits() - 1) } else { String::from("0") };
                            self.line(&format!("if ({} == {}) hrc_overflow(9, {});", a, min, loc));
                            self.line(&format!("{} = ({})(-{});", t, c, a));
                            return v(t);
                        }
                        v(format!("({})(-{})", self.g.ctype(&e.ty), a))
                    }
                    UnOp::Not => {
                        if e.ty == Ty::Bool {
                            v(format!("(!{})", a))
                        } else {
                            v(format!("({})(~{})", self.g.ctype(&e.ty), a))
                        }
                    }
                    UnOp::Deref => v(format!("(*{})", a)),
                }
            }
            K::Binary(op, a, b) => {
                let ops = self.binops(a, b);
                let (x, y) = match (&ops[0], &ops[1]) {
                    (Op::Val(x), Op::Val(y)) => (x.clone(), y.clone()),
                    _ => return Op::Never,
                };
                v(self.binary(*op, &x, &y, &a.ty, &e.ty, span))
            }
            K::And(a, b) | K::Or(a, b) => {
                let is_and = matches!(e.kind, K::And(..));
                let t = self.temp(&Ty::Bool);
                let x = self.expr(a);
                self.assign_to(&t, &x, &Ty::Bool);
                self.line(&format!("if ({}{}) {{", if is_and { "" } else { "!" }, t));
                self.indent += 1;
                let y = self.expr(b);
                self.assign_to(&t, &y, &Ty::Bool);
                self.indent -= 1;
                self.line("}");
                v(t)
            }
            K::Cast(x) => {
                let a = self.expr(x);
                let Op::Val(a) = a else { return Op::Never };
                v(self.cast(&a, &x.ty, &e.ty))
            }
            K::Slice(base, lo, hi) => {
                let b = match self.place_or_temp(base) {
                    Some(b) => b,
                    None => return Op::Never,
                };
                let lo = match lo {
                    Some(x) => self.value_temp(x).s(),
                    None => String::from("0"),
                };
                let (len, ptr) = match &base.ty {
                    Ty::Array(_, n) => (
                        format!(
                            "{}UL",
                            match &**n {
                                Ty::Const(n) => *n,
                                _ => 0,
                            }
                        ),
                        format!("{}.a", b),
                    ),
                    _ => (format!("{}.len", b), format!("{}.ptr", b)),
                };
                let hi = match hi {
                    Some(x) => self.value_temp(x).s(),
                    None => len.clone(),
                };
                let loc = self.loc(span);
                if base.ty == Ty::Str {
                    self.line(&format!("hrc_str_slice_check({}, {}, {}, {});", b, lo, hi, loc));
                } else {
                    self.line(&format!("hrc_slice_check({}, {}, {}, {});", lo, hi, len, loc));
                }
                let t = self.temp(&e.ty);
                self.line(&format!("{}.ptr = {} + {};", t, ptr, lo));
                self.line(&format!("{}.len = {} - {};", t, hi, lo));
                v(t)
            }
            K::Adt(def, fields) => self.adt(*def, fields, &e.ty, span),
            K::Tuple(fields) => {
                let ops = self.operands(fields);
                if ops.iter().any(|o| matches!(o, Op::Never)) {
                    return Op::Never;
                }
                let t = self.temp(&e.ty);
                for (i, (o, f)) in ops.iter().zip(fields.iter()).enumerate() {
                    self.assign_to(&format!("{}.f{}", t, i), o, &f.ty);
                }
                v(t)
            }
            K::Array(elems) => {
                let ops = self.operands(elems);
                if ops.iter().any(|o| matches!(o, Op::Never)) {
                    return Op::Never;
                }
                let t = self.temp(&e.ty);
                for (i, (o, f)) in ops.iter().zip(elems.iter()).enumerate() {
                    self.assign_to(&format!("{}.a[{}]", t, i), o, &f.ty);
                }
                v(t)
            }
            K::Repeat(x, n) => {
                let o = self.value_temp(x);
                if matches!(o, Op::Never) {
                    return Op::Never;
                }
                let t = self.temp(&e.ty);
                if *n > 0 && !is_zst_c(&x.ty) {
                    let i = self.temp(&Ty::usize());
                    self.line(&format!("for ({} = 0; {} < {}UL; {}++) {}.a[{}] = {};", i, i, n, i, t, i, o.s()));
                }
                v(t)
            }
            K::Closure(id, caps) => {
                let ops = self.operands(caps);
                let t = self.temp(&e.ty);
                for (i, (o, c)) in ops.iter().zip(caps.iter()).enumerate() {
                    self.assign_to(&format!("{}.c{}", t, i), o, &c.ty);
                }
                let _ = id;
                v(t)
            }
            K::Unsize(x) => {
                let a = self.expr(x);
                let Op::Val(a) = a else { return Op::Never };
                v(self.unsize(&a, &x.ty, &e.ty))
            }
            K::Block(stmts, tail) => {
                for s in stmts {
                    self.stmt(s);
                }
                self.expr(tail)
            }
            K::If(c, t, f) => {
                let cv = self.expr(c);
                let Op::Val(cv) = cv else { return Op::Never };
                let r = if is_zst_c(&e.ty) { None } else { Some(self.temp(&e.ty)) };
                self.line(&format!("if ({}) {{", cv));
                self.indent += 1;
                let tv = self.expr(t);
                if let Some(r) = &r {
                    self.assign_to(r, &tv, &e.ty);
                }
                self.indent -= 1;
                self.line("} else {");
                self.indent += 1;
                let fv = self.expr(f);
                if let Some(r) = &r {
                    self.assign_to(r, &fv, &e.ty);
                }
                self.indent -= 1;
                self.line("}");
                if matches!(e.ty, Ty::Never) {
                    return Op::Never;
                }
                v(r.unwrap_or_else(|| String::from("0")))
            }
            K::Match(s, arms) => self.match_(s, arms, &e.ty, span),
            K::Loop(body, id) => {
                let r = if is_zst_c(&e.ty) { None } else { Some(self.temp(&e.ty)) };
                let cont = self.new_label();
                let brk = self.new_label();
                self.labels.insert(*id, (brk.clone(), cont.clone(), r.clone()));
                self.label(&cont);
                self.expr(body);
                self.line(&format!("goto {};", cont));
                self.label(&brk);
                if matches!(e.ty, Ty::Never) {
                    return Op::Never;
                }
                v(r.unwrap_or_else(|| String::from("0")))
            }
            K::LabeledBlock(body, id) => {
                let r = if is_zst_c(&e.ty) { None } else { Some(self.temp(&e.ty)) };
                let brk = self.new_label();
                self.labels.insert(*id, (brk.clone(), String::new(), r.clone()));
                let bv = self.expr(body);
                if let Some(r) = &r {
                    self.assign_to(r, &bv, &e.ty);
                }
                self.label(&brk);
                if matches!(e.ty, Ty::Never) {
                    return Op::Never;
                }
                v(r.unwrap_or_else(|| String::from("0")))
            }
            K::Break(id, val) => {
                let x = self.expr(val);
                let (brk, _, r) = self.labels.get(id).cloned().unwrap_or_default();
                if let Some(r) = r {
                    self.assign_to(&r, &x, &val.ty);
                }
                self.line(&format!("goto {};", brk));
                Op::Never
            }
            K::Continue(id) => {
                let (_, cont, _) = self.labels.get(id).cloned().unwrap_or_default();
                self.line(&format!("goto {};", cont));
                Op::Never
            }
            K::Return(x) => {
                let val = self.expr(x);
                if let Op::Val(s) = val {
                    if is_zst_c(&x.ty) {
                        self.line("return 0;");
                    } else {
                        self.line(&format!("return {};", s));
                    }
                }
                Op::Never
            }
            K::Assign(p, x) => {
                let val = self.expr(x);
                let val = match val {
                    Op::Val(s) if has_effects(p) && !is_zst_c(&x.ty) => {
                        let t = self.temp(&x.ty);
                        self.line(&format!("{} = {};", t, s));
                        Op::Val(t)
                    }
                    o => o,
                };
                if matches!(val, Op::Never) {
                    return Op::Never;
                }
                let dst = self.place(p);
                self.assign_to(&dst, &val, &x.ty);
                v(String::from("0"))
            }
            K::AssignOp(op, p, x) => {
                let val = self.value_temp(x);
                let Op::Val(val) = val else { return Op::Never };
                let dst = self.place(p);
                let r = self.binary(*op, &dst, &val, &p.ty, &p.ty, span);
                self.line(&format!("{} = {};", dst, r));
                v(String::from("0"))
            }
            K::Unreachable => {
                let loc = self.loc(span);
                self.line(&format!("hrc_unreachable({});", loc));
                Op::Never
            }
        }
    }

    fn int_lit(&self, x: u128, ty: &Ty) -> String {
        match ty {
            Ty::Int(it) => {
                let bits = x as u64;
                if it.signed() && (bits as i64) < 0 {
                    format!("(({}){}UL)", Gen::int_c(*it), bits)
                } else {
                    format!("(({}){}UL)", Gen::int_c(*it), bits)
                }
            }
            Ty::Float(_) => format!("{}.0", x),
            _ => format!("{}", x as u64),
        }
    }

    fn binops(&mut self, a: &'a Expr, b: &'a Expr) -> Vec<Op> {
        let x = if has_effects(b) && !matches!(a.kind, K::Int(_) | K::Float(_) | K::Bool(_) | K::Char(_)) {
            self.value_temp(a)
        } else {
            self.expr(a)
        };
        let y = self.expr(b);
        alloc::vec![x, y]
    }

    fn binary(&mut self, op: BinOp, x: &str, y: &str, lt: &Ty, rt: &Ty, span: Span) -> String {
        let sym = op.symbol();
        match lt {
            Ty::Int(it) => {
                let c = Gen::int_c(*it);
                match op {
                    BinOp::Eq | BinOp::Ne | BinOp::Lt | BinOp::Le | BinOp::Gt | BinOp::Ge => format!("({} {} {})", x, sym, y),
                    BinOp::BitAnd | BinOp::BitOr | BinOp::BitXor => format!("(({})({} {} {}))", c, x, sym, y),
                    BinOp::Div | BinOp::Rem => {
                        let t = self.temp(rt);
                        let loc = self.loc(span);
                        let code = if op == BinOp::Div { 4 } else { 5 };
                        self.line(&format!("if ({} == 0) hrc_overflow({}, {});", y, code, loc));
                        if it.signed() {
                            let min = format!("({})(1UL << {})", c, it.bits() - 1);
                            self.line(&format!("if ({} == ({})-1 && {} == {}) hrc_overflow({}, {});", y, c, x, min, code + 2, loc));
                        }
                        self.line(&format!("{} = ({})({} {} {});", t, c, x, sym, y));
                        t
                    }
                    BinOp::Shl | BinOp::Shr => {
                        let t = self.temp(rt);
                        if self.g.checks {
                            let loc = self.loc(span);
                            let code = if op == BinOp::Shl { 10 } else { 11 };
                            self.line(&format!("if ((uint64_t){} >= {}) hrc_overflow({}, {});", y, it.bits(), code, loc));
                        }
                        self.line(&format!("{} = ({})({} {} ({} & {}));", t, c, x, sym, y, it.bits() - 1));
                        t
                    }
                    BinOp::Add | BinOp::Sub | BinOp::Mul if self.g.checks => {
                        let t = self.temp(rt);
                        let loc = self.loc(span);
                        let code = match op {
                            BinOp::Add => 1,
                            BinOp::Sub => 2,
                            _ => 3,
                        };
                        if it.bits() < 64 {
                            // Compute in 64 bits and check the range.
                            let wide = if it.signed() { "int64_t" } else { "int64_t" };
                            let w = self.temp(&Ty::Int(IntTy::I64));
                            self.line(&format!("{} = ({}){} {} ({}){};", w, wide, x, sym, wide, y));
                            let (lo, hi) = if it.signed() {
                                (-(1i64 << (it.bits() - 1)), (1i64 << (it.bits() - 1)) - 1)
                            } else {
                                (0, ((1u64 << it.bits()) - 1) as i64)
                            };
                            self.line(&format!("if ({} < {}L || {} > {}L) hrc_overflow({}, {});", w, lo, w, hi, code, loc));
                            self.line(&format!("{} = ({}){};", t, c, w));
                        } else if it.signed() {
                            self.line(&format!("{} = (int64_t)((uint64_t){} {} (uint64_t){});", t, x, sym, y));
                            let cond = match op {
                                BinOp::Add => format!("(({} >= 0) == ({} >= 0)) && (({} >= 0) != ({} >= 0))", x, y, t, x),
                                BinOp::Sub => format!("(({} >= 0) != ({} >= 0)) && (({} >= 0) != ({} >= 0))", x, y, t, x),
                                _ => format!(
                                    "({} != 0 && ({} / {} != {} || ({} == -1 && {} == (int64_t)(1UL << 63))))",
                                    x, t, x, y, x, y
                                ),
                            };
                            self.line(&format!("if ({}) hrc_overflow({}, {});", cond, code, loc));
                        } else {
                            self.line(&format!("{} = {} {} {};", t, x, sym, y));
                            let cond = match op {
                                BinOp::Add => format!("{} < {}", t, x),
                                BinOp::Sub => format!("{} < {}", x, y),
                                _ => format!("{} != 0 && {} / {} != {}", x, t, x, y),
                            };
                            self.line(&format!("if ({}) hrc_overflow({}, {});", cond, code, loc));
                        }
                        t
                    }
                    _ => format!("(({})({} {} {}))", c, x, sym, y),
                }
            }
            Ty::Float(ft) => match op {
                BinOp::Rem => {
                    if *ft == FloatTy::F32 {
                        format!("fmodf({}, {})", x, y)
                    } else {
                        format!("fmod({}, {})", x, y)
                    }
                }
                _ => format!("({} {} {})", x, sym, y),
            },
            Ty::Bool => match op {
                BinOp::BitAnd => format!("({} & {})", x, y),
                BinOp::BitOr => format!("({} | {})", x, y),
                BinOp::BitXor => format!("({} ^ {})", x, y),
                _ => format!("({} {} {})", x, sym, y),
            },
            _ => format!("({} {} {})", x, sym, y),
        }
    }

    fn cast(&mut self, a: &str, from: &Ty, to: &Ty) -> String {
        if from == to {
            return String::from(a);
        }
        let tc = self.g.ctype(to);
        match (from, to) {
            (Ty::Float(_), Ty::Int(it)) => {
                if it.signed() {
                    let lo = -(1i128 << (it.bits().min(64) - 1));
                    let hi = (1i128 << (it.bits().min(64) - 1)) - 1;
                    format!("(({})hrc_f2i((double){}, {}L, {}L))", tc, a, lo as i64, hi as i64)
                } else {
                    let hi = if it.bits() >= 64 { u64::MAX } else { (1u64 << it.bits()) - 1 };
                    format!("(({})hrc_f2u((double){}, {}UL))", tc, a, hi)
                }
            }
            (Ty::Int(it), Ty::Float(ft)) if !it.signed() && it.bits() == 64 => {
                if *ft == FloatTy::F32 {
                    format!("((float)hrc_u2f({}))", a)
                } else {
                    format!("hrc_u2f({})", a)
                }
            }
            (Ty::Adt(..), Ty::Int(_)) => format!("(({}){}.tag)", tc, a),
            // Fat to fat pointer: the same representation.
            (Ty::Ref(_, inner) | Ty::Ptr(_, inner), Ty::Ptr(_, to) | Ty::Ref(_, to)) if inner.is_unsized() && to.is_unsized() => String::from(a),
            (Ty::Ref(_, inner) | Ty::Ptr(_, inner), Ty::Ptr(..) | Ty::Int(_)) if inner.is_unsized() => format!("(({}){}.ptr)", tc, a),
            (Ty::Char, Ty::Int(_)) | (Ty::Bool, Ty::Int(_)) => format!("(({}){})", tc, a),
            _ => format!("(({}){})", tc, a),
        }
    }

    fn unsize(&mut self, a: &str, from: &Ty, to: &Ty) -> String {
        let inner = |t: &Ty| -> Ty {
            match t {
                Ty::Ref(_, x) | Ty::Ptr(_, x) => (**x).clone(),
                Ty::Adt(_, args) => args[0].clone(),
                _ => t.clone(),
            }
        };
        let src = inner(from);
        let dst = inner(to);
        let t = self.temp(to);
        match (&src, &dst) {
            (Ty::Array(_, n), Ty::Slice(_)) => {
                let n = match &**n {
                    Ty::Const(n) => *n,
                    _ => 0,
                };
                self.line(&format!("{}.ptr = (void *){}->a;", t, a));
                self.line(&format!("{}.len = {}UL;", t, n));
            }
            (_, Ty::Dyn(dy)) => {
                let vt = self
                    .g
                    .p
                    .vtables
                    .iter()
                    .position(|v| v.trait_ == dy.trait_ && v.ty == src)
                    .unwrap_or(0);
                self.line(&format!("{}.data = (void *){};", t, a));
                self.line(&format!("{}.vt = VT{};", t, vt));
            }
            _ => self.line(&format!("{} = {};", t, a)),
        }
        t
    }

    fn reify(&mut self, c: &'a Callee, ty: &Ty) -> String {
        match c {
            Callee::Inst(id) => self.g.fn_name(*id),
            Callee::Extern(d) => {
                self.g.externs.insert(*d);
                self.g.extern_name(*d)
            }
            Callee::Ctor(def, substs) => self.ctor_shim(*def, substs, ty),
            Callee::Closure(_, id) => {
                // A closure without captures as a plain function.
                let key = format!("reify closure {}", id);
                let name = format!("cr{}", id);
                if !self.g.shims.contains_key(&key) {
                    let (ps, r) = match ty {
                        Ty::FnPtr(ps, r) => (ps.to_vec(), (**r).clone()),
                        _ => (Vec::new(), crate::ty::unit()),
                    };
                    let rc = self.g.ctype(&r);
                    let env = self.g.ctype(&Ty::Closure(*id));
                    let mut params = Vec::new();
                    let mut args = alloc::vec![String::from("&e")];
                    for (i, p) in ps.iter().enumerate() {
                        let c = self.g.ctype(p);
                        params.push(format!("{} a{}", c, i));
                        args.push(format!("a{}", i));
                    }
                    if params.is_empty() {
                        params.push(String::from("void"));
                    }
                    let s = format!(
                        "static {} {}({}) {{\n    {} e;\n    return c{}({});\n}}\n",
                        rc,
                        name,
                        params.join(", "),
                        env,
                        id,
                        args.join(", ")
                    );
                    self.g.shims.insert(key, s);
                }
                name
            }
            _ => String::from("0"),
        }
    }

    fn ctor_shim(&mut self, def: DefId, substs: &Rc<[Ty]>, ty: &Ty) -> String {
        let key = format!("ctor {} {:?}", def, substs);
        if let Some(s) = self.g.shims.get(&key) {
            return s.lines().next().unwrap().split('(').next().unwrap().rsplit(' ').next().unwrap().to_string();
        }
        let (ps, r) = match ty {
            Ty::FnPtr(ps, r) => (ps.to_vec(), (**r).clone()),
            _ => (Vec::new(), crate::ty::unit()),
        };
        let name = self.g.fresh("ctor");
        let rc = self.g.ctype(&r);
        let mut params = Vec::new();
        let mut body = format!("    {} r;\n", rc);
        let (vi, is_enum) = match self.g.db.def(def).kind {
            DefKind::Variant(i) => (i, true),
            _ => (0, false),
        };
        if is_enum {
            let _ = writeln!(body, "    r.tag = {};", self.g.enum_disc(def));
        }
        for (i, p) in ps.iter().enumerate() {
            let c = self.g.ctype(p);
            params.push(format!("{} a{}", c, i));
            if is_zst_c(p) {
                continue;
            }
            if is_enum {
                let _ = writeln!(body, "    r.u.v{}.f{} = a{};", vi, i, i);
            } else {
                let _ = writeln!(body, "    r.f{} = a{};", i, i);
            }
        }
        if params.is_empty() {
            params.push(String::from("void"));
        }
        let s = format!("static {} {}({}) {{\n{}    return r;\n}}\n", rc, name, params.join(", "), body);
        self.g.shims.insert(key, s);
        name
    }

    fn adt(&mut self, def: DefId, fields: &'a [Expr], ty: &Ty, _span: Span) -> Op {
        let ops = self.operands(fields);
        if ops.iter().any(|o| matches!(o, Op::Never)) {
            return Op::Never;
        }
        let t = self.temp(ty);
        match self.g.db.def(def).kind {
            DefKind::Variant(vi) => {
                let d = self.g.enum_disc(def);
                self.line(&format!("{}.tag = {};", t, d));
                for (i, (o, f)) in ops.iter().zip(fields.iter()).enumerate() {
                    self.assign_to(&format!("{}.u.v{}.f{}", t, vi, i), o, &f.ty);
                }
            }
            _ => {
                for (i, (o, f)) in ops.iter().zip(fields.iter()).enumerate() {
                    self.assign_to(&format!("{}.f{}", t, i), o, &f.ty);
                }
            }
        }
        Op::Val(t)
    }

    fn call(&mut self, c: &'a Callee, args: &'a [Expr], ret: &Ty, span: Span) -> Op {
        if let Callee::Ctor(def, _) = c {
            return self.adt(*def, args, ret, span);
        }
        if let Callee::Builtin(b, substs) = c {
            return self.builtin(b, substs, args, ret, span);
        }
        // The callee expression first (closures, function pointers).
        let callee_place = match c {
            Callee::Closure(x, _) => Some(match self.place_or_temp(x) {
                Some(p) => p,
                None => return Op::Never,
            }),
            Callee::Value(x) => Some(match self.expr(x) {
                Op::Val(s) => s,
                Op::Never => return Op::Never,
            }),
            _ => None,
        };
        let ops = self.operands(args);
        if ops.iter().any(|o| matches!(o, Op::Never)) {
            return Op::Never;
        }
        let mut a: Vec<String> = ops.iter().map(|o| o.s()).collect();
        let f = match c {
            Callee::Inst(id) => {
                if self.g.p.fns[*id as usize].track_caller {
                    let l = self.loc(span);
                    a.push(l);
                }
                self.g.fn_name(*id)
            }
            Callee::Extern(d) => {
                self.g.externs.insert(*d);
                self.g.extern_name(*d)
            }
            Callee::Value(_) => format!("({})", callee_place.unwrap()),
            Callee::Closure(_, id) => {
                a.insert(0, format!("&{}", callee_place.unwrap()));
                format!("c{}", id)
            }
            Callee::Virtual(..) | Callee::DynFn if !a.is_empty() => {
                let slot = match c {
                    Callee::Virtual(_, s) => *s,
                    _ => 0,
                };
                let recv = a[0].clone();
                let r = self.g.ctype(ret);
                let mut ptys = alloc::vec![String::from("void *")];
                for x in &args[1..] {
                    ptys.push(self.g.ctype(&x.ty));
                }
                a[0] = format!("{}.data", recv);
                format!("(({} (*)({})){}.vt[{}])", r, ptys.join(", "), recv, slot)
            }
            _ => String::from("hrc_bad_callee"),
        };
        let call = format!("{}({})", f, a.join(", "));
        if matches!(ret, Ty::Never) {
            self.line(&format!("{};", call));
            return Op::Never;
        }
        if is_zst_c(ret) {
            self.line(&format!("{};", call));
            return Op::Val(String::from("0"));
        }
        let t = self.temp(ret);
        self.line(&format!("{} = {};", t, call));
        Op::Val(t)
    }

    fn builtin(&mut self, b: &'a Builtin, substs: &Rc<[Ty]>, args: &'a [Expr], ret: &Ty, span: Span) -> Op {
        let ops = self.operands(args);
        if ops.iter().any(|o| matches!(o, Op::Never)) {
            return Op::Never;
        }
        let a: Vec<String> = ops.iter().map(|o| o.s()).collect();
        let t0 = substs.first().cloned().unwrap_or(Ty::Error);
        let r = match b {
            Builtin::Clone(parts) => {
                // args[0]: &T
                if parts.is_empty() {
                    if is_zst_c(&t0) {
                        return Op::Val(String::from("0"));
                    }
                    format!("(*{})", a[0])
                } else {
                    let t = self.temp(&t0);
                    match &t0 {
                        Ty::Tuple(ts) => {
                            for (i, (p, et)) in parts.iter().zip(ts.iter()).enumerate() {
                                let v = self.clone_part(p, &format!("(&(*{}).f{})", a[0], i), et, span);
                                if !is_zst_c(et) {
                                    self.line(&format!("{}.f{} = {};", t, i, v));
                                }
                            }
                        }
                        Ty::Array(et, n) => {
                            let n = match &**n {
                                Ty::Const(n) => *n,
                                _ => 0,
                            };
                            let i = self.temp(&Ty::usize());
                            self.line(&format!("for ({} = 0; {} < {}UL; {}++) {{", i, i, n, i));
                            self.indent += 1;
                            let v = self.clone_part(&parts[0], &format!("(&(*{}).a[{}])", a[0], i), et, span);
                            self.line(&format!("{}.a[{}] = {};", t, i, v));
                            self.indent -= 1;
                            self.line("}");
                        }
                        _ => self.line(&format!("{} = *{};", t, a[0])),
                    }
                    return Op::Val(t);
                }
            }
            Builtin::Intrinsic(name) => match self.intrinsic(name, substs, &a, args, ret, span) {
                Some(s) => s,
                None => return Op::Never,
            },
        };
        if matches!(ret, Ty::Never) {
            self.line(&format!("{};", r));
            return Op::Never;
        }
        if is_zst_c(ret) {
            if r.contains('(') {
                self.line(&format!("{};", r));
            }
            return Op::Val(String::from("0"));
        }
        Op::Val(r)
    }

    fn clone_part(&mut self, c: &'a Callee, arg: &str, ty: &Ty, span: Span) -> String {
        match c {
            Callee::Inst(id) => {
                let mut args = alloc::vec![String::from(arg)];
                if self.g.p.fns[*id as usize].track_caller {
                    let l = self.loc(span);
                    args.push(l);
                }
                let f = self.g.fn_name(*id);
                if is_zst_c(ty) {
                    self.line(&format!("{}({});", f, args.join(", ")));
                    return String::from("0");
                }
                format!("{}({})", f, args.join(", "))
            }
            Callee::Builtin(Builtin::Clone(parts), _) if parts.is_empty() => format!("(*{})", arg),
            Callee::Builtin(Builtin::Clone(parts), _) => {
                // Nested tuples/arrays: clone through a temporary.
                let t = self.temp(ty);
                match ty {
                    Ty::Tuple(ts) => {
                        for (i, (p, et)) in parts.iter().zip(ts.iter()).enumerate() {
                            let v = self.clone_part(p, &format!("(&(*{}).f{})", arg, i), et, span);
                            if !is_zst_c(et) {
                                self.line(&format!("{}.f{} = {};", t, i, v));
                            }
                        }
                    }
                    Ty::Array(et, n) => {
                        let n = match &**n {
                            Ty::Const(n) => *n,
                            _ => 0,
                        };
                        let i = self.temp(&Ty::usize());
                        self.line(&format!("for ({} = 0; {} < {}UL; {}++) {{", i, i, n, i));
                        let v = self.clone_part(&parts[0], &format!("(&(*{}).a[{}])", arg, i), et, span);
                        self.line(&format!("{}.a[{}] = {};", t, i, v));
                        self.line("}");
                    }
                    _ => {}
                }
                t
            }
            _ => format!("(*{})", arg),
        }
    }

    /// Compiler intrinsics used by the standard library.
    fn intrinsic(&mut self, name: &str, substs: &Rc<[Ty]>, a: &[String], args: &'a [Expr], ret: &Ty, span: Span) -> Option<String> {
        let t0 = substs.first().cloned().unwrap_or(Ty::Error);
        let rc = self.g.ctype(ret);
        Some(match name {
            "size_of" => {
                if is_zst_c(&t0) || matches!(&t0, Ty::Tuple(ts) if ts.is_empty()) {
                    String::from("0UL")
                } else {
                    let c = self.g.ctype(&t0);
                    format!("((uint64_t)sizeof({}))", c)
                }
            }
            "ptr_read" => format!("(*{})", a[0]),
            "ptr_write" => {
                if !is_zst_c(&t0) {
                    self.line(&format!("*{} = {};", a[0], a[1]));
                }
                String::from("0")
            }
            "ptr_add" => format!("({} + {})", a[0], a[1]),
            "ptr_sub" => format!("({} - {})", a[0], a[1]),
            "ptr_diff" => format!("((int64_t)({} - {}))", a[0], a[1]),
            "ptr_null" => format!("(({})0)", rc),
            "ptr_copy" => {
                if !is_zst_c(&t0) {
                    let c = self.g.ctype(&t0);
                    self.line(&format!("memmove({}, {}, {} * sizeof({}));", a[1], a[0], a[2], c));
                }
                String::from("0")
            }
            "char_from_u32_unchecked" => format!("((uint32_t){})", a[0]),
            "from_raw" | "into_raw" => format!("(({}){})", rc, a[0]),
            "str_from_raw" | "slice_from_raw" | "slice_from_raw_mut" => {
                let t = self.temp(ret);
                self.line(&format!("{}.ptr = (void *){};", t, a[0]));
                self.line(&format!("{}.len = {};", t, a[1]));
                t
            }
            "str_ptr" | "slice_ptr" => format!("(({}){}.ptr)", rc, a[0]),
            "str_len" | "slice_len" => format!("{}.len", a[0]),
            "discriminant" => format!("((int64_t)(*{}).tag)", a[0]),
            "abort" => {
                let loc = self.loc(span);
                self.line(&format!("hrc_unreachable({});", loc));
                return None;
            }
            "caller_location" => self.loc(span),
            "wrapping_add" | "wrapping_sub" | "wrapping_mul" => {
                let sym = match name {
                    "wrapping_add" => "+",
                    "wrapping_sub" => "-",
                    _ => "*",
                };
                match &t0 {
                    Ty::Int(it) if it.signed() => {
                        let u = Gen::int_c(match it {
                            IntTy::I8 => IntTy::U8,
                            IntTy::I16 => IntTy::U16,
                            IntTy::I32 => IntTy::U32,
                            _ => IntTy::U64,
                        });
                        format!("(({})(({}){} {} ({}){}))", rc, u, a[0], sym, u, a[1])
                    }
                    _ => format!("(({})({} {} {}))", rc, a[0], sym, a[1]),
                }
            }
            "overflowing_add" | "overflowing_sub" | "overflowing_mul" => {
                // Returns (T, bool).
                let op = match name {
                    "overflowing_add" => BinOp::Add,
                    "overflowing_sub" => BinOp::Sub,
                    _ => BinOp::Mul,
                };
                let it = match &t0 {
                    Ty::Int(it) => *it,
                    _ => IntTy::I64,
                };
                let c = Gen::int_c(it);
                let t = self.temp(ret);
                let sym = op.symbol();
                if it.bits() < 64 {
                    let w = self.temp(&Ty::Int(IntTy::I64));
                    self.line(&format!("{} = (int64_t){} {} (int64_t){};", w, a[0], sym, a[1]));
                    let (lo, hi) = if it.signed() {
                        (-(1i64 << (it.bits() - 1)), (1i64 << (it.bits() - 1)) - 1)
                    } else {
                        (0, ((1u64 << it.bits()) - 1) as i64)
                    };
                    self.line(&format!("{}.f0 = ({}){};", t, c, w));
                    self.line(&format!("{}.f1 = {} < {}L || {} > {}L;", t, w, lo, w, hi));
                } else if it.signed() {
                    let (x, y) = (&a[0], &a[1]);
                    self.line(&format!("{}.f0 = (int64_t)((uint64_t){} {} (uint64_t){});", t, x, sym, y));
                    let r = format!("{}.f0", t);
                    let cond = match op {
                        BinOp::Add => format!("(({} >= 0) == ({} >= 0)) && (({} >= 0) != ({} >= 0))", x, y, r, x),
                        BinOp::Sub => format!("(({} >= 0) != ({} >= 0)) && (({} >= 0) != ({} >= 0))", x, y, r, x),
                        _ => format!("({} != 0 && ({} / {} != {} || ({} == -1 && {} == (int64_t)(1UL << 63))))", x, r, x, y, x, y),
                    };
                    self.line(&format!("{}.f1 = {};", t, cond));
                } else {
                    let (x, y) = (&a[0], &a[1]);
                    self.line(&format!("{}.f0 = {} {} {};", t, x, sym, y));
                    let r = format!("{}.f0", t);
                    let cond = match op {
                        BinOp::Add => format!("{} < {}", r, x),
                        BinOp::Sub => format!("{} < {}", x, y),
                        _ => format!("{} != 0 && {} / {} != {}", x, r, x, y),
                    };
                    self.line(&format!("{}.f1 = {};", t, cond));
                }
                t
            }
            "f64_to_bits" | "f32_to_bits" | "f64_from_bits" | "f32_from_bits" => {
                let (from, to) = match name {
                    "f64_to_bits" => ("double", "uint64_t"),
                    "f32_to_bits" => ("float", "uint32_t"),
                    "f64_from_bits" => ("uint64_t", "double"),
                    _ => ("uint32_t", "float"),
                };
                let t = self.temp(ret);
                let tmp = self.g.fresh("u");
                let _ = writeln!(self.decls, "    union {{ {} a; {} b; }} {};", from, to, tmp);
                self.line(&format!("{}.a = {};", tmp, a[0]));
                self.line(&format!("{} = {}.b;", t, tmp));
                t
            }
            "type_name" => {
                let n: Rc<str> = Rc::from(self.g.tyname(&t0).as_str());
                self.g.str_const(&n)
            }
            "transmute_ref" => format!("(({}){})", rc, a[0]),
            "needs_drop" => String::from("0"),
            _ => {
                let _ = args;
                let loc = self.loc(span);
                self.line(&format!("/* unknown intrinsic {} */ hrc_unreachable({});", name, loc));
                return None;
            }
        })
    }

    // ---- match and patterns ----

    fn match_(&mut self, s: &'a Expr, arms: &'a [tir::Arm], ty: &Ty, span: Span) -> Op {
        let place = match self.place_or_temp(s) {
            Some(p) => p,
            None => return Op::Never,
        };
        let r = if is_zst_c(ty) { None } else { Some(self.temp(ty)) };
        let end = self.new_label();
        for arm in arms {
            let next = self.new_label();
            self.pat(&arm.pat, &place, &next);
            if let Some(g) = &arm.guard {
                let gv = self.expr(g);
                self.line(&format!("if (!{}) goto {};", gv.s(), next));
            }
            let bv = self.expr(&arm.body);
            if let Some(r) = &r {
                self.assign_to(r, &bv, ty);
            }
            if !matches!(bv, Op::Never) {
                self.line(&format!("goto {};", end));
            }
            self.label(&next);
        }
        let loc = self.loc(span);
        self.line(&format!("hrc_unreachable({});", loc));
        self.label(&end);
        if matches!(ty, Ty::Never) {
            return Op::Never;
        }
        Op::Val(r.unwrap_or_else(|| String::from("0")))
    }

    /// Tests `place` against a pattern (jumping to `fail` on mismatch) and
    /// binds its variables.
    fn pat(&mut self, p: &'a Pat, place: &str, fail: &str) {
        match &p.kind {
            PatKind::Wild => {}
            PatKind::Bind(l, mode, sub) => {
                if let Some(s) = sub {
                    self.pat(s, place, fail);
                }
                let lt = self.locals()[*l as usize].ty.clone();
                if is_zst_c(&lt) {
                    return;
                }
                match mode {
                    Some(_) if p.ty.is_unsized() => self.line(&format!("l{} = {};", l, place)),
                    Some(_) => self.line(&format!("l{} = &{};", l, place)),
                    None => self.line(&format!("l{} = {};", l, place)),
                }
            }
            PatKind::Const(e) => {
                let v = self.expr(e).s();
                match &p.ty {
                    Ty::Ref(_, inner) if **inner == Ty::Str => {
                        self.line(&format!("if (!hrc_str_eq({}, {})) goto {};", place, v, fail));
                    }
                    t if is_zst_c(t) => {}
                    _ => self.line(&format!("if ({} != {}) goto {};", place, v, fail)),
                }
            }
            PatKind::Range(lo, hi, incl) => {
                if let Some(lo) = lo {
                    let v = self.expr(lo).s();
                    self.line(&format!("if ({} < {}) goto {};", place, v, fail));
                }
                if let Some(hi) = hi {
                    let v = self.expr(hi).s();
                    let op = if *incl { ">" } else { ">=" };
                    self.line(&format!("if ({} {} {}) goto {};", place, op, v, fail));
                }
            }
            PatKind::Adt(def, fields) => {
                let mut prefix = String::from(place);
                if let Some(d) = def {
                    if let DefKind::Variant(vi) = self.g.db.def(*d).kind {
                        let disc = self.g.enum_disc(*d);
                        self.line(&format!("if ({}.tag != {}) goto {};", place, disc, fail));
                        prefix = format!("{}.u.v{}", place, vi);
                    }
                }
                for (i, fp) in fields {
                    let sub = format!("{}.f{}", prefix, i);
                    self.pat(fp, &sub, fail);
                }
            }
            PatKind::Deref(inner) => {
                if inner.ty.is_unsized() {
                    self.pat(inner, place, fail);
                } else {
                    let sub = format!("(*{})", place);
                    self.pat(inner, &sub, fail);
                }
            }
            PatKind::Or(alts) => {
                let ok = self.new_label();
                for a in alts {
                    let next = self.new_label();
                    self.pat(a, place, &next);
                    self.line(&format!("goto {};", ok));
                    self.label(&next);
                }
                self.line(&format!("goto {};", fail));
                self.label(&ok);
            }
            PatKind::Slice(pre, rest, suf) => {
                let (len, elems) = match &p.ty {
                    Ty::Array(_, n) => (
                        format!(
                            "{}UL",
                            match &**n {
                                Ty::Const(n) => *n,
                                _ => 0,
                            }
                        ),
                        format!("{}.a", place),
                    ),
                    _ => (format!("{}.len", place), format!("{}.ptr", place)),
                };
                let fixed = pre.len() + suf.len();
                if rest.is_none() {
                    self.line(&format!("if ({} != {}) goto {};", len, fixed, fail));
                } else if fixed > 0 {
                    self.line(&format!("if ({} < {}) goto {};", len, fixed, fail));
                }
                for (i, x) in pre.iter().enumerate() {
                    let sub = format!("{}[{}]", elems, i);
                    self.pat(x, &sub, fail);
                }
                for (j, x) in suf.iter().enumerate() {
                    let sub = format!("{}[{} - {} + {}]", elems, len, suf.len(), j);
                    self.pat(x, &sub, fail);
                }
                if let Some(r) = rest {
                    if let PatKind::Bind(l, mode, _) = &r.kind {
                        let lt = self.locals()[*l as usize].ty.clone();
                        let _ = mode;
                        match &r.ty {
                            Ty::Slice(_) => {
                                // A fat pointer to the middle.
                                self.line(&format!("l{}.ptr = {} + {};", l, elems, pre.len()));
                                self.line(&format!("l{}.len = {} - {};", l, len, fixed));
                            }
                            _ => {
                                let c = self.g.ctype(&r.ty);
                                if matches!(lt, Ty::Ref(..)) {
                                    self.line(&format!("l{} = ({} *)&{}[{}];", l, c, elems, pre.len()));
                                } else {
                                    self.line(&format!("memmove(&l{}, &{}[{}], sizeof(l{}));", l, elems, pre.len(), l));
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}

fn float_lit(f: f64, ty: &Ty) -> String {
    let s = if f.is_nan() {
        String::from("(0.0/0.0)")
    } else if f.is_infinite() {
        String::from(if f > 0.0 { "(1.0/0.0)" } else { "(-1.0/0.0)" })
    } else {
        format!("{:e}", f)
    };
    match ty {
        Ty::Float(FloatTy::F32) => format!("((float){})", s),
        _ => format!("((double){})", s),
    }
}
