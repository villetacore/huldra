//! C code generation from the typed IR.
//!
//! Every expression is lowered to statements over temporaries, so all
//! control flow (`break`, `?`, `match` arms) is plain `goto` between
//! statements. Types become C structs named `T<n>`; references to `str`,
//! slices and trait objects are fat pointers.

use crate::ast::{BinOp, UnOp};
use crate::resolve::{Db, DefId, DefKind};
use crate::tir::{self, Builtin, Callee, Expr, ExprKind as K, Pat, PatKind, Program, Stmt};
use crate::ty::{FloatTy, IntTy, Ty};
use crate::{Options, Sources, Span};
use alloc::collections::{BTreeMap, BTreeSet};
use alloc::format;
use alloc::rc::Rc;
use alloc::string::{String, ToString};
use alloc::vec::Vec;
use core::fmt::Write;

pub fn generate(db: &Db, p: &Program, sources: &Sources, options: &Options) -> String {
    let mut g = Gen {
        db,
        p,
        sources,
        checks: options.overflow_checks,
        names: BTreeMap::new(),
        defined: BTreeSet::new(),
        fwd: String::new(),
        defs: String::new(),
        consts: String::new(),
        protos: String::new(),
        fns: String::new(),
        strs: BTreeMap::new(),
        locs: BTreeMap::new(),
        shims: BTreeMap::new(),
        externs: BTreeSet::new(),
        n: 0,
    };
    g.run()
}

struct Gen<'a> {
    db: &'a Db,
    p: &'a Program,
    sources: &'a Sources,
    checks: bool,
    names: BTreeMap<Ty, String>,
    defined: BTreeSet<Ty>,
    fwd: String,
    defs: String,
    consts: String,
    protos: String,
    fns: String,
    strs: BTreeMap<Rc<str>, String>,
    locs: BTreeMap<Span, String>,
    shims: BTreeMap<String, String>,
    externs: BTreeSet<DefId>,
    n: usize,
}

